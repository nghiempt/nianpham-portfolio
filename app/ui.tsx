export type IconName = keyof typeof ICONS;
export const isIconName = (name: string): name is IconName => name in ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export function Icon({ name, size = 18 }: { name: IconName; size?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {ICONS[name]}
    </svg>
  );
}

/**
 * macOS-style app icon tile. Pass `src` for an image (logo or photo), or
 * `glyph` + `accent` to draw a line icon on a tinted tile.
 */
export function AppIcon({
  src,
  glyph,
  accent,
  photo,
  size,
}: {
  src?: string;
  glyph?: IconName;
  accent?: string;
  photo?: boolean;
  size: number;
}) {
  if (glyph) {
    return (
      <span
        className="app-icon is-glyph"
        style={{ width: size, height: size, "--p-accent": accent } as CSSProperties}
        aria-hidden="true"
      >
        <Icon name={glyph} size={Math.round(size * 0.56)} />
      </span>
    );
  }
  return (
    <span className={`app-icon${photo ? " is-photo" : ""}`} style={{ width: size, height: size }} aria-hidden="true">
      {src && (
        <Image
          src={src}
          alt=""
          width={size}
          height={size}
          sizes={`${size * 2}px`}
          style={photo ? { objectPosition: "center 20%" } : undefined}
        />
      )}
    </span>
  );
}
